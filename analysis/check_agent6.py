"""
Automatic checks on the Agent 6 rationales stored in outputs/run_log.json.
Standalone, read-only on run_log.json; writes analysis/agent6_check_report.md.

Per lead time it checks:
  1. Sentence count: the rationale should be 3-5 sentences (bold-only title lines are not counted).
  2. Numbers: every number and date in the rationale must appear in the prompt payload, which is rebuilt
     with agents.agent6_synthesis._build_prompt from the stored numeric_summary. Unmatched ones are listed.
  3. Labels: the words CONFIRMED and DERIVED must both appear, and no sentence may carry both a
     CONFIRMED-only figure and a DERIVED-only figure unless it has both a confirmed label
     (CONFIRMED/official) and a derived label (DERIVED/simulat...).
  4. Rate-of-rise: the sentence(s) giving the flag's x-baseline ratio, and whether each carries an
     explicit DERIVED tag (strict) or only attributes the figure to the pipeline's own check or estimate.

Heuristics, report only; nothing is fixed. Limits: numbers are matched as digits, so numbers written as
words ("one day") are not checked, and sentence splitting is regex-based.

Usage: python analysis/check_agent6.py [path/to/run_log.json]
"""
import json
import os
import re
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO_ROOT)
from agents import agent6_synthesis  # noqa: E402

RUN_LOG_PATH = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO_ROOT, "outputs", "run_log.json")
REPORT_OUT = os.path.join(REPO_ROOT, "analysis", "agent6_check_report.md")
ORDER = ("T-72h", "D0", "T-24h", "T-48h")  # T-72h first: the paper quotes it

DATE = re.compile(r"\d{4}-\d{2}-\d{2}")


def numbers(text):
    """(set of ISO dates, set of numbers) after dropping unit and label tokens that contain digits."""
    dates = set(DATE.findall(text))
    t = DATE.sub(" ", text)
    t = re.sub(r"\bT-\d+h\b|\bD0\b|Mm3|Mm³|m3|m³|2026/\d+", " ", t)
    return dates, {float(x) for x in re.findall(r"\d+(?:\.\d+)?", t)}


def sentences(text):
    body = []
    for ln in text.splitlines():
        s = ln.strip()
        if not s or set(s) <= set("-*_ "):
            continue
        if re.fullmatch(r"\*\*[^*]+\*\*|#+ .*|\*\([^)]*\)\*", s):  # bold-only title / heading / italic subtitle
            continue
        body.append(s)
    para = re.sub(r"(?<=\d)\.(?=\d)", "<DOT>", " ".join(body))  # protect decimals
    parts = re.split(r"(?<=[.!?])\s+(?=[A-Z(\*\"'])", para)
    return [p.replace("<DOT>", ".").strip() for p in parts if p.strip()]


def has(s, pattern):
    return re.search(pattern, s, re.I) is not None


def check(lead_time, entry):
    text = entry["rationale"]
    prompt = agent6_synthesis._build_prompt(lead_time, entry["numeric_summary"])
    p_dates, p_nums = numbers(prompt)
    i_der, i_con = prompt.index("DERIVED (Agent 2"), prompt.index("CONFIRMED (dam_parameters")
    d_dates, d_nums = numbers(prompt[i_der:i_con])
    c_dates, c_nums = numbers(prompt[i_con:])
    conf_only, der_only = (c_nums - d_nums, c_dates - d_dates), (d_nums - c_nums, d_dates - c_dates)

    r_dates, r_nums = numbers(text)
    sents = sentences(text)
    res = {
        "n_sentences": len(sents),
        "bad_numbers": sorted(n for n in r_nums if not any(abs(n - a) < 1e-9 for a in p_nums)),
        "bad_dates": sorted(r_dates - p_dates),
        "has_confirmed": "CONFIRMED" in text, "has_derived": "DERIVED" in text,
        "mixed_unlabeled": [], "confirmed_unlabeled": [], "derived_unlabeled": [], "rate_of_rise": [],
    }
    for s in sents:
        sd, sn = numbers(s)
        has_c = bool((sn & conf_only[0]) or (sd & conf_only[1]))
        has_d = bool((sn & der_only[0]) or (sd & der_only[1]))
        lab_c, lab_d = has(s, r"CONFIRMED|official"), has(s, r"DERIVED|simulat")
        if has_c and has_d and not (lab_c and lab_d):
            res["mixed_unlabeled"].append(s)
        if has_c and not lab_c:
            res["confirmed_unlabeled"].append(s)
        if has_d and not lab_d:
            res["derived_unlabeled"].append(s)

    m = re.search(r"\(([\d.]+)x baseline", entry["numeric_summary"]["first_flag_summary"])
    if m:  # a rate-of-rise flag exists for this lead time: find the sentence(s) giving its ratio
        ratio = m.group(1)
        for s in sents:
            if re.search(re.escape(ratio) + r"\s*(x|times)\b", s):
                res["rate_of_rise"].append({"sentence": s, "ratio": ratio, "explicit_derived_tag": "DERIVED" in s,
                                            "attributed_to_pipeline": has(s, r"pipeline|simulat|estimated")})
    return res


def main():
    log = json.load(open(RUN_LOG_PATH, encoding="utf-8"))["agent6_decision_synthesis"]["by_lead_time"]
    results = {lt: check(lt, log[lt]) for lt in ORDER}

    out = ["# Agent 6 rationale checks", "",
           "Generated by `analysis/check_agent6.py` from `outputs/run_log.json` (heuristic checks, nothing is fixed; "
           "see the script docstring for limits).", "",
           "| Lead time | Isolation | Model returned | Sentences (3-5) | Numbers/dates not in payload | CONFIRMED / DERIVED words | "
           "Unlabeled confirmed+derived mix | Rate-of-rise ratio: explicit DERIVED tag |",
           "|---|---|---|---|---|---|---|---|"]
    for lt in ORDER:
        r, e = results[lt], log[lt]
        ror = r["rate_of_rise"]
        out.append(
            f"| {lt} | {e.get('agent6_isolation')} | {e.get('agent6_model_id_returned')} | "
            f"{r['n_sentences']} ({'OK' if 3 <= r['n_sentences'] <= 5 else 'outside 3-5'}) | "
            f"{(r['bad_numbers'] + r['bad_dates']) or 'none'} | "
            f"{'both present' if r['has_confirmed'] and r['has_derived'] else 'MISSING'} | "
            f"{len(r['mixed_unlabeled'])} | "
            f"{('yes' if all(x['explicit_derived_tag'] for x in ror) else 'no') if ror else 'no flag / not found'} |")
    out += ["", "## Details", ""]
    for lt in ORDER:
        r = results[lt]
        out += [f"### {lt}", "",
                f"- Sentences: {r['n_sentences']}",
                f"- Numbers not in payload: {r['bad_numbers'] or 'none'}; dates not in payload: {r['bad_dates'] or 'none'}",
                f"- Sentences mixing a confirmed-only and a derived-only figure without both labels: {len(r['mixed_unlabeled'])}"]
        out += [f"  - > {s}" for s in r["mixed_unlabeled"]]
        out.append(f"- Rate-of-rise ratio sentence(s): {len(r['rate_of_rise']) or 'none found'}")
        for x in r["rate_of_rise"]:
            out.append(f"  - ratio {x['ratio']}x; explicit DERIVED tag: {x['explicit_derived_tag']}; "
                       f"attributed to the pipeline's own check or estimate: {x['attributed_to_pipeline']}")
            out.append(f"    > {x['sentence']}")
        out.append(f"- (soft) sentences with a derived-only figure but no DERIVED/simulat wording: {len(r['derived_unlabeled'])}")
        out += [f"  - > {s}" for s in r["derived_unlabeled"]]
        out.append(f"- (soft) sentences with a confirmed-only figure but no CONFIRMED/official wording: {len(r['confirmed_unlabeled'])}")
        out += [f"  - > {s}" for s in r["confirmed_unlabeled"]]
        out.append("")
    report = "\n".join(out)
    with open(REPORT_OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(report)
    print(report)
    print(f"\nWrote {os.path.relpath(REPORT_OUT, REPO_ROOT)}")


if __name__ == "__main__":
    main()
